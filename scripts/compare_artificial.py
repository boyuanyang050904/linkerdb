"""Natural (linkerdb) vs synthetic (G4S)n / (EAAAK)n linkers.

Regenerates docs/artificial_comparison.md and results/db/artificial_comparison.csv from
the built database. Honest framing: this shows what a natural-linker library *adds*
(a large, diverse, experimentally-characterised pool, especially of rigid connectors),
not that natural linkers outperform synthetic ones in any construct.

Usage: python scripts/compare_artificial.py [DB_DIR]
"""

import collections
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from linkerdb.artificial import artificial_table  # noqa: E402

AA = "ACDEFGHIKLMNPQRSTVWY"
RIGID = {"rigid", "rigid_helical", "strand_spanning"}
FLEX = {"flexible", "flexible_disordered"}
db = Path(sys.argv[1] if len(sys.argv) > 1 else "results/db")
C = pd.read_parquet(db / "linkers_canonical.parquet")
hi = C[C["rigidity_confidence"] == "high"]   # rigidity is only trustworthy at high confidence


def composition(seqs):
    c = collections.Counter("".join(s for s in seqs if isinstance(s, str)))
    tot = sum(c[a] for a in AA) or 1
    return {a: 100 * c[a] / tot for a in AA}


def pool_row(name, sub):
    return {
        "pool": name, "n": len(sub),
        "length_median": round(sub["length_median"].median(), 0),
        "length_5_95": f"{sub['length_median'].quantile(.05):.0f}-{sub['length_median'].quantile(.95):.0f}",
        "coil": int((sub["linker_class"] == "coil").sum()),
        "helix": int((sub["linker_class"] == "helix_spanning").sum()),
        "strand": int((sub["linker_class"] == "strand_spanning").sum()),
        "pct_human": round(100 * sub["is_human"].mean(), 0),
        "pct_liability_free": round(100 * (sub["liability_score"] == 0).mean(), 0),
    }


R = hi[hi["rigidity"].isin(RIGID)]
F = hi[hi["rigidity"].isin(FLEX)]
pools = pd.DataFrame([pool_row("rigid", R), pool_row("flexible", F)])

art = artificial_table()

# rigid natural linkers binned by end-to-end span: "I need an ~N Å rigid spacer"
rc = R[(R["linker_class"] == "coil") & R["end_to_end_median"].notna()].copy()
rc["span_bin"] = pd.cut(rc["end_to_end_median"], [0, 8, 14, 20, 26, 100],
                        labels=["<8", "8-14", "14-20", "20-26", ">26"])
span_tbl = rc.groupby("span_bin", observed=True).agg(
    n=("canonical_id", "size"), median_len=("length_median", "median"),
    pct_liability_free=("liability_score", lambda s: round(100 * (s == 0).mean()))).reset_index()

fc = composition(F[F["linker_class"] == "coil"]["coil_sequence"])
top_flex = sorted(fc, key=fc.get, reverse=True)[:8]


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join("" if v is None or (isinstance(v, float) and pd.isna(v)) else
                                      (",".join(v) if isinstance(v, list) else str(v)) for v in r) + " |")
    return "\n".join(out)


doc = f"""# Natural linkers (linkerdb) vs synthetic (G4S)n / (EAAAK)n

Generated by `scripts/compare_artificial.py` from the built database
(high-confidence rigidity calls only). This shows what the natural-linker library
**adds**; it is not a claim that natural linkers outperform synthetic ones in a
given construct — any candidate still has to be modelled and tested.

## The two standard synthetic linkers

{md_table(art)}

Both are liability-free by design. `(G4S)n` is the default flexible choice; `(EAAAK)n`
is essentially the *only* common rigid choice, and it is a single alpha-helix whose
only tunable is the number of turns.

## What linkerdb adds

{md_table(pools)}

The headline: a fusion-protein designer who needs a **rigid** connector has, in
practice, one synthetic option (EAAAK). linkerdb offers **{len(R)}** high-confidence
rigid natural linkers — {int((R['linker_class']=='coil').sum())} coil, {int((R['linker_class']=='helix_spanning').sum())} continuous-helix and {int((R['linker_class']=='strand_spanning').sum())} continuous-strand —
each with an experimentally-observed structure, {pool_row('rigid', R)['pct_liability_free']:.0f}% of them liability-free and
{pool_row('rigid', R)['pct_human']:.0f}% human-derived.

### Rigid coil linkers by end-to-end span (pick a spacer length)

{md_table(span_tbl)}

## Composition

`(G4S)n` is 80% Gly + 20% Ser; `(EAAAK)n` is 60% Ala + 20% Glu + 20% Lys. Natural
flexible linkers are enriched in the same small/polar residues **but are far more
diverse** — top residues (coil, flexible): {', '.join(f'{a} {fc[a]:.0f}%' for a in top_flex)}.
Proline and the charged residues (Asp/Glu/Lys) are prominent, which `(G4S)n` lacks;
these are exactly the handles one reaches for to add rigidity, solubility or
protease resistance without leaving natural sequence space.

## Honest takeaways

1. `(G4S)n` was a reasonable design — Gly/Ser are genuinely enriched in natural
   flexible linkers — but it samples only a corner of natural flexible-linker space.
2. For **rigid** connectors the synthetic toolkit is essentially one helix (EAAAK);
   the database's main value is a large, length- and shape-diverse pool of natural
   rigid linkers with real structures.
3. Natural linkers are mostly liability-free too, and the ones that are not are
   flagged, so you keep the safety of the synthetic options while gaining choice.
4. ~1 in 6 are human-derived, an option with no synthetic analogue.
5. This does **not** say natural beats synthetic in function; it says you have many
   more structurally-characterised starting points. Model and test the shortlist.
"""

out_md = Path("docs/artificial_comparison.md")
out_md.write_text(doc)
rc_out = pd.concat([pools.assign(kind="natural_pool"),
                    art.rename(columns={"name": "pool"}).assign(kind="synthetic")], ignore_index=True)
rc_out.to_csv(db / "artificial_comparison.csv", index=False)
print(f"wrote {out_md} and {db / 'artificial_comparison.csv'}")
print(pools.to_string(index=False))
